// Ejercicio 05: operadores aritméticos, de comparación y lógicos.
const a = 10;
const b = 3;
console.log("Suma:", a + b);
console.log("Resta:", a - b);
console.log("Multiplicación:", a * b);
console.log("División:", a / b);
console.log("Residuo:", a % b);
console.log("Potencia:", a ** b);
console.log("¿a es mayor que b?:", a > b);
console.log("¿a es igual estrictamente a b?:", a === b);
console.log("¿a > 5 Y b < 5?:", a > 5 && b < 5);
console.log("¿a < 5 O b < 5?:", a < 5 || b < 5);
console.log("Negación de verdadero:", !true);
