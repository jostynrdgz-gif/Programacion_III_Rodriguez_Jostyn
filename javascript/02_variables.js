// Ejercicio 02: declaración y uso de variables.
let nombre = "Jostyn"; // let permite cambiar el valor.
const carrera = "Desarrollo de Software"; // const no permite reasignación.
var semestre = 2; // var es una forma antigua de declarar variables.
console.log("Nombre:", nombre);
console.log("Carrera:", carrera);
console.log("Semestre:", semestre);
nombre = "Jostyn Rodríguez";
console.log("Nombre actualizado:", nombre);
