// Ejercicio 07: selección de opciones con switch.
const opcion = 2;
switch (opcion) {
  case 1:
    console.log("Elegiste consultar información");
    break;
  case 2:
    console.log("Elegiste registrar un dato");
    break;
  case 3:
    console.log("Elegiste salir");
    break;
  default:
    console.log("Opción no válida");
}
